//! `cgr prompt-hook`: the Claude Code `UserPromptSubmit` hook (design doc 11.2). Reads the
//! prompt, and when it mentions code the index knows, prints the explore result as extra context.
//! Every failure ends in exit code 0 with no output: the hook must never get in the user's way.

use cg_core::brand;
use cg_query::explore::ExploreOptions;
use cg_query::search::{tokenize_query, TokKind};
use cg_query::{Project, SearchOptions};
use cg_store::Store;
use std::io::Read;
use std::path::{Path, PathBuf};

/// Claude Code shows up to 10,000 characters of hook output inline.
const MAX_OUTPUT: usize = 9_000;

const STRUCTURAL: &[&str] = &[
    "how does",
    "how do",
    "how is",
    "where is",
    "where are",
    "where does",
    "flow",
    "architecture",
    "who calls",
    "callers",
    "callees",
    "depends on",
    "implement",
    "refactor",
    "trace",
    "explain",
    "what calls",
    "impact",
    "call path",
    "call chain",
    "walk me through",
    "怎么",
    "如何",
    "流程",
    "调用",
    "实现",
    "在哪",
    "架构",
    "影响",
];

fn strip_system_reminders(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(a) = rest.find("<system-reminder>") {
        out.push_str(&rest[..a]);
        match rest[a..].find("</system-reminder>") {
            Some(b) => rest = &rest[a + b + "</system-reminder>".len()..],
            None => {
                rest = "";
                break;
            }
        }
    }
    out.push_str(rest);
    out
}

/// Task notifications, sub-agent hand-backs and compaction summaries are not questions.
fn is_machine_message(p: &str) -> bool {
    let t = p.trim_start();
    t.starts_with("<task-notification")
        || t.starts_with("<local-command")
        || t.starts_with("This session is being continued")
        || t.starts_with("Caveat: The messages below were generated by the user")
        || t.starts_with("[Request interrupted")
}

/// Nearest index at or above `cwd`; for a monorepo root without one, a sub-project below it.
fn find_project(cwd: &Path, prompt_words: &[String]) -> Option<(Store, bool)> {
    if let Some(s) = Store::locate(cwd) {
        return Some((s, false));
    }
    let mut found: Vec<PathBuf> = Vec::new();
    let mut frontier = vec![cwd.to_path_buf()];
    for _ in 0..3 {
        let mut next = Vec::new();
        for d in frontier {
            let Ok(rd) = std::fs::read_dir(&d) else { continue };
            for e in rd.flatten() {
                let p = e.path();
                let name = e.file_name().to_string_lossy().into_owned();
                if !p.is_dir() || name.starts_with('.') || matches!(name.as_str(), "node_modules" | "target" | "vendor" | "dist" | "build") {
                    continue;
                }
                if p.join(brand::DATA_DIR).join("manifest").is_file() {
                    found.push(p);
                } else {
                    next.push(p);
                }
            }
        }
        frontier = next;
        if found.len() >= 8 {
            break;
        }
    }
    found.sort();
    // prefer the sub-project whose name the prompt mentions
    let pick = found
        .iter()
        .find(|p| p.file_name().is_some_and(|n| prompt_words.iter().any(|w| w.eq_ignore_ascii_case(&n.to_string_lossy()))))
        .or_else(|| found.first())
        .cloned()?;
    Some((Store::at(&pick), true))
}

fn compute(prompt: &str, cwd: &Path) -> Option<String> {
    let prompt = strip_system_reminders(prompt);
    if prompt.trim().is_empty() || is_machine_message(&prompt) {
        return None;
    }
    let toks = tokenize_query(&prompt);
    let words: Vec<String> = toks.iter().map(|t| t.raw.clone()).collect();
    let (store, sub_project) = find_project(cwd, &words)?;
    let project = Project::open(store).ok()?;
    let g = &project.graph;
    let lower = prompt.to_lowercase();
    let structural = STRUCTURAL.iter().any(|k| lower.contains(k));
    let code_known = toks.iter().any(|t| match t.kind {
        TokKind::Code | TokKind::Qualified => !g.resolve_symbol(&t.raw).is_empty(),
        TokKind::Path => !g.files_matching(&t.raw).is_empty(),
        TokKind::Plain => false,
    });
    let hint = if sub_project {
        format!(" The project is at `{}`: pass it as projectPath to the {}explore tool.", project.root().display(), brand::MCP_TOOL_PREFIX)
    } else {
        String::new()
    };
    if structural || code_known {
        let opts = ExploreOptions { max_output: Some(MAX_OUTPUT - 400), ..Default::default() };
        let r = g.explore(&prompt, &opts);
        if r.symbols > 0 || r.found_named {
            let note = format!(
                "{} pre-fetched this for the prompt: verbatim source and call paths of the code it mentions. Treat the source as already Read.{hint}",
                brand::PROJECT_NAME
            );
            return Some(format!("<codegraph_context note=\"{note}\">\n{}\n</codegraph_context>", r.text));
        }
    }
    // plain words that only match parts of symbol names: a short list
    let plain: Vec<_> = toks.iter().filter(|t| t.kind == TokKind::Plain && t.raw.len() >= 4).cloned().collect();
    if !plain.is_empty() {
        let hits = g.search_tokens(&plain, &SearchOptions { limit: 6, fuzzy: false, ..Default::default() });
        let hits: Vec<_> = hits.into_iter().filter(|h| h.score >= 45.0).collect();
        if !hits.is_empty() {
            let list: Vec<String> =
                hits.iter().map(|h| format!("{} ({}, {}:{})", g.name(h.node), g.kind(h.node), g.node_path(h.node), g.line(h.node))).collect();
            let note = format!(
                "indexed symbols whose names match words in the prompt; call the {}explore tool with these names for their source.{hint}",
                brand::MCP_TOOL_PREFIX
            );
            return Some(format!("<codegraph_context note=\"{note}\">\n{}\n</codegraph_context>", list.join("\n")));
        }
    }
    None
}

pub fn run() -> i32 {
    if brand::env::get(brand::env::NO_PROMPT_HOOK, Some(brand::env::NO_PROMPT_HOOK_UPSTREAM)).is_some_and(|v| v == "1") {
        return 0;
    }
    #[cfg(unix)]
    if unsafe { libc::isatty(0) } == 1 {
        return 0;
    }
    let mut input = String::new();
    if std::io::stdin().take(4 << 20).read_to_string(&mut input).is_err() {
        return 0;
    }
    let Ok(v) = serde_json::from_str::<serde_json::Value>(&input) else { return 0 };
    let Some(prompt) = v.get("prompt").and_then(|p| p.as_str()).map(str::to_owned) else { return 0 };
    let cwd = v.get("cwd").and_then(|c| c.as_str()).map(PathBuf::from).or_else(|| std::env::current_dir().ok()).unwrap_or_default();
    let out = std::panic::catch_unwind(|| compute(&prompt, &cwd)).ok().flatten();
    if let Some(text) = out {
        use std::io::Write;
        let mut so = std::io::stdout().lock();
        let _ = so.write_all(text.as_bytes());
        let _ = so.write_all(b"\n");
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_reminders_are_removed() {
        assert_eq!(strip_system_reminders("a <system-reminder>secret</system-reminder> b"), "a  b");
        assert_eq!(strip_system_reminders("a <system-reminder>unterminated"), "a ");
    }

    #[test]
    fn machine_messages_are_skipped() {
        assert!(is_machine_message("<task-notification>done</task-notification>"));
        assert!(is_machine_message("This session is being continued from a previous conversation"));
        assert!(!is_machine_message("how does login work?"));
    }
}
